#include "codegen/codegen.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* Helper to map CPU and memory to standard instance types */
static const char *map_aws_instance_type(int cpu, double mem_gb)
{
    if (cpu <= 1 && mem_gb <= 1.0)  return "t3.micro";
    if (cpu <= 1 && mem_gb <= 2.0)  return "t3.small";
    if (cpu <= 2 && mem_gb <= 4.0)  return "t3.medium";
    if (cpu <= 2 && mem_gb <= 8.0)  return "t3.large";
    if (cpu <= 4 && mem_gb <= 16.0) return "t3.xlarge";
    if (cpu <= 8 && mem_gb <= 32.0) return "t3.2xlarge";
    return "m5.large";
}

char *codegen_generate_terraform(const CLARA_IR *ir)
{
    if (ir == NULL)
    {
        return NULL;
    }

    size_t buf_size = 8192;
    char *hcl = (char *)malloc(buf_size);
    if (hcl == NULL)
    {
        return NULL;
    }

    size_t offset = 0;

    offset += snprintf(hcl + offset, buf_size - offset,
        "# Automatically generated by CLARA Compiler\n"
        "# Target Provider: %s | Region: %s\n\n",
        ir->provider, ir->region
    );

    /* Provider block */
    if (strcmp(ir->provider, "aws") == 0)
    {
        offset += snprintf(hcl + offset, buf_size - offset,
            "provider \"aws\" {\n"
            "  region = \"%s\"\n"
            "}\n\n",
            ir->region
        );
    }
    else if (strcmp(ir->provider, "azure") == 0)
    {
        offset += snprintf(hcl + offset, buf_size - offset,
            "provider \"azurerm\" {\n"
            "  features {}\n"
            "}\n\n"
        );
    }
    else if (strcmp(ir->provider, "gcp") == 0)
    {
        offset += snprintf(hcl + offset, buf_size - offset,
            "provider \"google\" {\n"
            "  region = \"%s\"\n"
            "}\n\n",
            ir->region
        );
    }
    else
    {
        offset += snprintf(hcl + offset, buf_size - offset,
            "# Generic Provider: %s\n\n", ir->provider
        );
    }

    /* Compute instances */
    size_t i;
    for (i = 0; i < ir->server_count; i++)
    {
        const IRServer *s = &ir->servers[i];
        const char *inst_type = map_aws_instance_type(s->cpu, s->memory_gb);

        offset += snprintf(hcl + offset, buf_size - offset,
            "resource \"aws_instance\" \"%s\" {\n"
            "  ami           = \"ami-0c55b159cbfafe1f0\" # Ubuntu 22.04 LTS\n"
            "  instance_type = \"%s\" # %d vCPU, %.1f GB RAM\n\n"
            "  root_block_device {\n"
            "    volume_size = %.0f # GB\n"
            "    volume_type = \"gp3\"\n"
            "  }\n\n"
            "  tags = {\n"
            "    Name = \"%s\"\n"
            "    ManagedBy = \"CLARA\"\n"
            "  }\n"
            "}\n\n",
            s->name, inst_type, s->cpu, s->memory_gb, s->storage_gb, s->name
        );
    }

    /* Databases */
    for (i = 0; i < ir->database_count; i++)
    {
        const IRDatabase *db = &ir->databases[i];

        offset += snprintf(hcl + offset, buf_size - offset,
            "resource \"aws_db_instance\" \"%s\" {\n"
            "  identifier        = \"%s\"\n"
            "  engine            = \"postgres\"\n"
            "  instance_class    = \"db.t3.medium\"\n"
            "  allocated_storage = %.0f # GB\n"
            "  skip_final_snapshot = true\n\n"
            "  tags = {\n"
            "    Name = \"%s\"\n"
            "    ManagedBy = \"CLARA\"\n"
            "  }\n"
            "}\n\n",
            db->name, db->name, db->storage_gb, db->name
        );
    }

    return hcl;
}
